"""The appendix table of MoE traffic at n = 256 (Chen K19): every engine, every Radix base.

Same layout as moe_tab_summary.tex (the n = 8 table it replaces): engine x setup rows, and for
T_parallel, N and C/S one column per trace family (throughput, MMLU). Each cell is the mean over
the family's 18 matrices of the moe256 campaign (moe256_campaign.py); C/S is the mean of the
per-matrix ratios, as Figure 7 plots it.
Writes moe256_tab_summary.tex into the paper folder.
Run with BVN_CAMPAIGN=2026_11 BVN_RUN_ROOT=run/rerun_2026_11e.
"""
from __future__ import annotations
from _paths import PAPER, REPO
import os
from datetime import datetime
import pandas as pd

RUN = os.environ.get("BVN_RUN_ROOT", "run")
res = pd.read_csv(os.path.join(str(REPO), RUN, "moe256", "moe256_results.csv"))
m = res.groupby(["engine", "config", "regime"])[["runtime_ms", "N", "C_over_S"]].mean()
ENGINES = ["Hungarian", "GW Dynamic", "GW Static", "WWFA"]
CFGS = [("BvN", "Unsplit"), ("B16", "$B=16$"), ("B8", "$B=8$"), ("B4", "$B=4$"), ("B2", "$B=2$")]
FAM = ["MoE throughput", "MoE mmlu"]


def num(x, dec=0):
    return f"{x:,.{dec}f}".replace(",", "{,}")


out = [f"% MoE traffic at n = 256, every engine and Radix base; mean over 18 matrices per family",
       f"% Generated by agent_scripts/make_moe256_table.py on {datetime.now():%Y-%m-%d %H:%M}.",
       f"% Source: {RUN}/moe256/moe256_results.csv. Do not edit by hand: rerun the script instead.",
       "",
       r"\begin{tabular}{ll rr rr rr}", r"\toprule",
       r"& & \multicolumn{2}{c}{$\TPc$ (ms)} & \multicolumn{2}{c}{$N$} & \multicolumn{2}{c}{$C/S$} \\",
       r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(lr){7-8}",
       r"\textbf{Engine} & \textbf{Splitting} & Thr. & MMLU & Thr. & MMLU & Thr. & MMLU \\",
       r"\midrule"]
for i, e in enumerate(ENGINES):
    out.append(rf"\multirow{{{len(CFGS)}}}{{*}}{{{e}}}")
    for c, lab in CFGS:
        r = [m.loc[(e, c, f)] for f in FAM]
        out.append(f"  & {lab} & {num(r[0].runtime_ms)} & {num(r[1].runtime_ms)} & "
                   f"{num(r[0].N)} & {num(r[1].N)} & {r[0].C_over_S:.3f} & {r[1].C_over_S:.3f} \\\\")
    out.append(r"\midrule" if i < len(ENGINES) - 1 else r"\bottomrule")
out.append(r"\end{tabular}")
path = os.path.join(str(PAPER), "moe256_tab_summary.tex")
open(path, "w", encoding="utf-8").write("\n".join(out) + "\n")
print("wrote", path)
print("\n".join(out[10:18]))
