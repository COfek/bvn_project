"""Generate the three Chapter 6 tables from the variance campaign.

These three tables previously had no generator anywhere in the repository. They
had been assembled by hand from four different campaign directories, one of
which AGENT_GUIDE.md marks "Superseded -- do not cite", so a single table could
carry its timings from one campaign and its cycles from another.

    tab_results_summary.tex    Radix across engines
    tab_euler_all_engines.tex  Euler across engines
    tab_euler_vs_radix.tex     Euler against Radix, on identical matrices

Source: run/variance_2026/sweep{1,2,3}/, three full repetitions of the campaign
run on 2026-08-30 and 2026-08-31 on an idle machine. Every reported time is the
mean over the three sweeps, so a single unlucky run cannot set a number, and the
script reports the spread between sweeps so the paper can state a reproducibility
figure. Cycle length and permutation count are deterministic given the seed and
are identical across all three; the script asserts that rather than assuming it.

The comparison table needed care. Euler campaigns run 105 matrices and the Radix
campaign 1000, and the generator seeds matrix i as random_seed + i, so the Euler
matrices are the Radix campaign's first 105. Restricting the Radix side to that
window makes the comparison exact: identical matrices, identical S.

Two traps this script avoids, both of which have bitten:
  * sweep3_contaminated must not be globbed in. It is the original sweep 3,
    measured while the machine was in use, kept as evidence.
  * the runner computes the BvN baseline only for engines in a gate list, so
    plain heavy/heavy_static/wfa runs have an empty bvn column and their
    baselines live under sweep*/baseline/ from a separate _bvn run.

Usage:  .venv/Scripts/python.exe agent_scripts/make_paper_tables.py
"""
from __future__ import annotations

import glob
import os
import sys
from datetime import datetime

import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from radix_extraction import add_to_radix_times, extraction_ms  # noqa: E402

ROOT = r"C:\Users\ofekc\Desktop\Msc\Thesis\bvn_project"
OUT = r"C:\Users\ofekc\Desktop\Msc\Thesis\paper"

WARMUP = 5          # matrices discarded to exclude JIT compilation, as 6.1 states
SWEEPS = (1, 2, 3)  # named, never globbed: sweep3_contaminated must stay out

# engine key in the CSV column names -> name used in the paper
ENGINES = [("max", "maximum", "Hungarian"),
           ("wfa", "wfa", "WFA"),
           ("heavy", "heavy", "GW Dynamic"),
           ("heavy_static", "heavy_static", "GW Static")]

BASES = [16, 8, 4, 2]
DEPTHS = [1, 2, 3, 4]

spreads: list[float] = []   # every between-sweep spread seen, for the summary


def newest(pattern: str) -> str:
    hits = sorted(glob.glob(os.path.join(ROOT, pattern)))
    if not hits:
        sys.exit(f"no campaign matches {pattern}")
    return hits[-1]


def frame(sweep: int, kind: str, engine: str, rows: int | None = None) -> pd.DataFrame:
    """One sweep's results for one engine. kind is radix, euler or baseline."""
    d = pd.read_csv(newest(f"run/variance_2026/sweep{sweep}/{kind}/{engine}/*/results_stats.csv"))
    if kind == "radix":
        # the campaign timed the slowest plane only; charge the digit extraction
        d = add_to_radix_times(d, "variance")
    d = d.iloc[WARMUP:]
    return d.iloc[:rows] if rows else d


def across(kind: str, engine: str, column: str, rows: int | None = None) -> float:
    """Mean of a column over the three sweeps, recording the spread between them."""
    per = [frame(s, kind, engine, rows)[column].mean() for s in SWEEPS]
    if per[0] and max(per) > 0:
        spreads.append((max(per) - min(per)) / (sum(per) / len(per)) * 100)
    return sum(per) / len(per)


def fixed(kind: str, engine: str, column: str, rows: int | None = None) -> float:
    """A deterministic quantity: identical across sweeps, and checked to be."""
    per = [frame(s, kind, engine, rows)[column].mean() for s in SWEEPS]
    assert max(per) - min(per) < 1e-6, (
        f"{kind}/{engine}/{column} differs between sweeps: {per}. "
        "Cycle and permutation counts are deterministic given the seed; if they "
        "differ, the sweeps are not the same experiment.")
    return per[0]


def baseline_source(dir_key: str) -> str:
    """Hungarian gets its baseline from the radix run; the others need the _bvn run."""
    return "radix" if dir_key == "max" else "baseline"


def stamp(path: str) -> str:
    return os.path.basename(os.path.dirname(path))


def header(title: str, sources: list[tuple[str, str]], n: int) -> str:
    lines = [f"% {title}",
             f"% Generated by agent_scripts/make_paper_tables.py on "
             f"{datetime.now().strftime('%Y-%m-%d %H:%M')}.",
             f"% Do not edit by hand: rerun the script instead.",
             f"% Times are the mean over {len(SWEEPS)} full repetitions of the campaign;",
             f"% cycle and permutation counts are identical across all of them.",
             f"% Sample: {n} matrices per sweep after discarding the first {WARMUP}.",
             "% Sources:"]
    lines += [f"%   {label:<12s} {path}" for label, path in sources]
    return "\n".join(lines) + "\n"


def bold_min(values, fmt):
    lo = min(values)
    return [(r"\textbf{" + fmt(v) + "}") if v == lo else fmt(v) for v in values]


def f1(v):
    return f"{v:.1f}"


def f0(v):
    return f"{v:.0f}"


# --------------------------------------------------------------------------
# Radix across engines
# --------------------------------------------------------------------------
def table_radix() -> str:
    sources, rows, n = [], [], None
    for dir_key, col_key, name in ENGINES:
        bsrc = baseline_source(dir_key)
        sources.append((name, f"sweep{{1,2,3}}/radix/{dir_key}/"
                              + ("" if bsrc == "radix" else f" + baseline/{dir_key}/")))
        n = len(frame(1, "radix", dir_key))
        times = [across(bsrc, dir_key, "bvn_runtime") * 1000] + \
                [across("radix", dir_key, f"{col_key}_{b}_time") * 1000 for b in BASES]
        cycles = [fixed(bsrc, dir_key, "bvn_cycle")] + \
                 [fixed("radix", dir_key, f"{col_key}_{b}_cycle") for b in BASES]
        perms = [fixed(bsrc, dir_key, "bvn_perms")] + \
                [fixed("radix", dir_key, f"{col_key}_{b}_perms") for b in BASES]
        labels = ["BvN baseline"] + [f"Radix $B={b}$" for b in BASES]
        rows.append((name, labels, bold_min(times, f1),
                     bold_min(cycles, f0), bold_min(perms, f0)))

    out = [header("Radix across engines, dense generated workload", sources, n),
           r"\begin{tabular}{llrrr}", r"\toprule",
           r"\textbf{Engine} & \textbf{Config} & \textbf{$\Tc$ (ms)} & "
           r"\textbf{Cycle} & \textbf{Perms} \\",
           r"\midrule"]
    for i, (name, labels, tc, tl, tp) in enumerate(rows):
        out.append(r"\multirow{5}{*}{" + name + "}")
        for lab, a, b, c in zip(labels, tc, tl, tp):
            out.append(f"  & {lab:<14s} & {a:<16s} & {b:<16s} & {c:<16s} \\\\")
        out.append(r"\midrule" if i < len(rows) - 1 else r"\bottomrule")
    out.append(r"\end{tabular}")
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------
# Euler across engines
# --------------------------------------------------------------------------
def table_euler() -> str:
    sources, rows, n = [], [], None
    for _dir_key, col_key, name in ENGINES:
        sources.append((name, f"sweep{{1,2,3}}/euler/{col_key}/"))
        n = len(frame(1, "euler", col_key))
        times = [across("euler", col_key, "bvn_runtime") * 1000] + \
                [across("euler", col_key, f"euler_heuristic_depth{k}_time") * 1000
                 for k in DEPTHS]
        cycles = [fixed("euler", col_key, "bvn_cycle")] + \
                 [fixed("euler", col_key, f"euler_heuristic_depth{k}_cycle") for k in DEPTHS]
        perms = [fixed("euler", col_key, "bvn_perms")] + \
                [fixed("euler", col_key, f"euler_heuristic_depth{k}_perms") for k in DEPTHS]
        labels = ["BvN baseline"] + [f"depth {k}" for k in DEPTHS]
        rows.append((name, labels, bold_min(times, f1),
                     bold_min(cycles, f0), bold_min(perms, f0)))

    out = [header("Euler splitting across engines, dense generated workload", sources, n),
           r"\begin{tabular}{llrrr}", r"\toprule",
           r"\textbf{Engine} & \textbf{Config} & \textbf{Max-leaf (ms)} & "
           r"\textbf{Cycle} & \textbf{Perms} \\", r"\midrule"]
    for i, (name, labels, tc, tl, tp) in enumerate(rows):
        out.append(r"\multirow{5}{*}{" + name + "}")
        for lab, a, b, c in zip(labels, tc, tl, tp):
            out.append(f"  & {lab:<13s} & {a:<16s} & {b:<16s} & {c:<16s} \\\\")
        out.append(r"\midrule" if i < len(rows) - 1 else r"\bottomrule")
    out.append(r"\end{tabular}")
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------
# Euler against Radix, on the SAME matrices
# --------------------------------------------------------------------------
def extraction_mean_ms(base: int, rows: int) -> float:
    """Mean digit-extraction time over the matrices a table covers (after warm-up)."""
    ext = extraction_ms("variance")
    idx = range(WARMUP, WARMUP + rows)
    return sum(ext[(i, base)] for i in idx) / len(idx)


def table_evr() -> str:
    n = len(frame(1, "euler", "maximum"))

    S_e = fixed("euler", "maximum", "bvn_cycle")
    S_r = fixed("radix", "max", "bvn_cycle", rows=n)
    assert abs(S_e - S_r) < 1e-6, (
        f"the two sides are not the same draw: S={S_e} vs {S_r}. "
        "The comparison in this table is only meaningful on identical matrices.")

    planes = {b: int(frame(1, "radix", "max", n)[f"maximum_{b}_planes"].mode().iloc[0])
              for b in BASES}
    pairs = [(1, [16, 8]), (2, [4]), (3, [2]), (4, [])]

    out = [header("Euler leaves against Radix digit planes, Hungarian engine, "
                  "identical matrices",
                  [("Euler", "sweep{1,2,3}/euler/maximum/"),
                   ("Radix", f"sweep{{1,2,3}}/radix/max/ (first {n} matrices, "
                             f"the window the Euler campaign covers)")], n),
           r"\begin{tabular}{lrrrrrr}", r"\toprule",
           r"\textbf{Config} & \textbf{Units} & \textbf{Max-unit (ms)} & "
           r"\textbf{Split (ms)} & \textbf{Total (ms)} & $C/S$ & \textbf{Perms} \\",
           r"\midrule"]

    for j, (depth, bases) in enumerate(pairs):
        pre = f"euler_heuristic_depth{depth}"
        e_unit = across("euler", "maximum", f"{pre}_time") * 1000
        e_split = across("euler", "maximum", f"{pre}_split") * 1000
        block = [(f"Euler depth {depth}", 2 ** depth, e_unit, e_split,
                  e_unit + e_split, fixed("euler", "maximum", f"{pre}_cycle") / S_e,
                  fixed("euler", "maximum", f"{pre}_perms"))]
        for b in bases:
            # the total now includes the digit extraction; report it in the split
            # column, as Euler's split is, and the slowest plane as the unit time
            total = across("radix", "max", f"maximum_{b}_time", rows=n) * 1000
            ext = extraction_mean_ms(b, n)
            block.append((f"Radix $B={b}$", planes[b], total - ext, ext, total,
                          fixed("radix", "max", f"maximum_{b}_cycle", rows=n) / S_r,
                          fixed("radix", "max", f"maximum_{b}_perms", rows=n)))

        totals = bold_min([r[4] for r in block], f1)
        ratios = bold_min([r[5] for r in block], lambda v: f"{v:.3f}")
        perms = bold_min([r[6] for r in block], f0)
        for (lab, units, unit, split, _t, _c, _p), tot, rat, per in zip(
                block, totals, ratios, perms):
            sp = r"$\sim$0" if split is None else f"{split:.1f}"
            out.append(f"{lab:<20s} & {units:<3d} & {unit:5.1f} & {sp:<7s} & "
                       f"{tot:<15s} & {rat:<15s} & {per} \\\\")
        if depth == 4:
            out.append(r"Radix (none)         & --- & ---   & ---     & --- "
                       r"           & ---            & --- \\")
        out.append(r"\midrule" if j < len(pairs) - 1 else r"\bottomrule")

    out.append(r"\end{tabular}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    for fname, build in (("tab_results_summary.tex", table_radix),
                         ("tab_euler_all_engines.tex", table_euler),
                         ("tab_euler_vs_radix.tex", table_evr)):
        text = build()
        with open(os.path.join(OUT, fname), "w", encoding="utf-8") as fh:
            fh.write(text)
        print(f"wrote {fname}  ({len(text.splitlines())} lines)")

    if spreads:
        spreads.sort()
        mid = spreads[len(spreads) // 2]
        print(f"\nbetween-sweep spread over {len(spreads)} timed cells: "
              f"median {mid:.1f}%, worst {spreads[-1]:.1f}%")
